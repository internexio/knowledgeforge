def print_manifest(manifest: list[dict], platform: str, dry_run: bool, diff_mode: bool):
    mode = "DRY RUN" if dry_run else ("DIFF" if diff_mode else "COMPILE")
    print(f"\nkf-compile [{mode}] → {platform}")
    print("=" * 60)

    counts = {"written": 0, "unchanged": 0, "changed": 0,
              "would_write": 0, "missing_section": 0}

    for entry in manifest:
        status = entry["status"]
        counts[status] = counts.get(status, 0) + 1

        if status == "unchanged":
            marker = "  ·"
        elif status in ("written", "would_write"):
            marker = "  +"
        elif status == "changed":
            marker = "  ~"
        elif status == "missing_section":
            marker = "  !"
        elif status == "diverged":
            marker = "  ⚠"
        else:
            marker = "  ?"

        line = f"{marker} {entry['output']}"
        if "diff_summary" in entry:
            line += f"  ({entry['diff_summary']})"
        if status == "missing_section":
            line += f"  ← MISSING section '## {entry['section']}' in {entry['source']}"
        if status == "diverged":
            line += f"  ← DIVERGED: {entry.get('diverged_reason', 'hand-edited')}"
        print(line)

    print("=" * 60)
    if dry_run:
        print(f"Would write: {counts.get('would_write', 0)}  "
              f"Skipped (missing section): {counts.get('missing_section', 0)}")
    elif diff_mode:
        print(f"Changed: {counts.get('changed', 0)}  "
              f"Unchanged: {counts.get('unchanged', 0)}  "
              f"Missing section: {counts.get('missing_section', 0)}")
    else:
        print(f"Written: {counts.get('written', 0)}  "
              f"Skipped (missing section): {counts.get('missing_section', 0)}  "
              f"Diverged (skipped): {counts.get('diverged', 0)}")


def _section_anchor(section: str) -> str:
    """Convert a section heading to a GitHub markdown anchor.

    '## CC Skill' → '#cc-skill'  (lowercase, spaces→hyphens, strip punctuation)
    """
    anchor = section.lower().replace(" ", "-")
    # GitHub strips most punctuation except hyphens and underscores
    anchor = re.sub(r"[^\w\-]", "", anchor)
    return f"#{anchor}"


def write_manifest(manifest: list[dict], output_root: Path, platform: str, version: str):
    """Write compilation manifest.

    - JSON → variant repo (machine-readable, tracked there)
    - MD load map → knowledgeforge-core root (human-navigable on GitHub)

    The MD lives in core so that relative links like `modules/02_builder.md#cc-skill`
    resolve correctly within the same GitHub repo. Cross-repo relative links don't
    work on GitHub, so the map must be co-located with the source modules.
    """
    ts = datetime.now(timezone.utc).isoformat()

    # --- JSON (machine-readable) → variant repo ---
    manifest_path = output_root / ".kf-compile-manifest.json"
    data = {
        "compiled_at": ts,
        "source": "knowledgeforge-core",
        "platform": platform,
        "version": version,
        "entries": manifest,
    }
    manifest_path.write_text(json.dumps(data, indent=2), encoding="utf-8")

    # --- Markdown load map (human-navigable) → core repo root ---
    # Links are relative to CORE_ROOT, so `modules/02_builder.md#cc-skill`
    # resolves on GitHub without any path gymnastics.
    # Deterministic load map: no timestamp embedded (was causing load-map-*.md
    # to show as modified on every compile even when no content changed —
    # noop git churn in core. The authoritative compiled_at lives in
    # .kf-compile-manifest.json in each variant repo). bead `rxc`.
    md_lines = [
        f"# KnowledgeForge Load Map — `{platform}`",
        f"",
        f"**Version:** `{version}`",
        f"",
        f"Each row shows one compiled output and the exact source section it was extracted from.",
        f"Click the source link to jump directly to that section in the module file.",
        f"",
        f"| Status | Output (variant repo) | Source module | Section |",
        f"|:---:|---|---|:---:|",
    ]

    for entry in manifest:
        status = entry.get("status", "")
        source = entry.get("source", "")
        section = entry.get("section", "full")
        output = entry.get("output", "")

        # Source link — relative from core repo root, GitHub resolves these natively.
        if section not in ("full", "copy") and source:
            anchor = _section_anchor(section)
            source_link = f"[`{source}`](modules/{source}{anchor})"
            section_label = f"`{section}`"
        elif section == "copy":
            source_link = f"`{source}`"
            section_label = "_verbatim_"
        else:
            source_link = f"[`{source}`](modules/{source})" if source else "—"
            section_label = "_full file_"

        badge = {
            "written": "✓", "unchanged": "·", "changed": "~",
            "missing_section": "⚠︎", "would_write": "?",
        }.get(status, status)

        output_cell = f"`{output}`" if output else "—"
        md_lines.append(f"| {badge} | {output_cell} | {source_link} | {section_label} |")

    md_lines += [
        "",
        "---",
        f"_Generated by `compiler/kf-compile.py`. Do not edit manually._",
        f"_JSON manifest (machine-readable) is at `.kf-compile-manifest.json` in the variant repo._",
    ]

    # Write to core root so relative links resolve on GitHub.
    # Named without a dot prefix so it's visible in GitHub's file listing.
    md_path = CORE_ROOT / f"load-map-{platform}.md"
    md_path.write_text("\n".join(md_lines) + "\n", encoding="utf-8")
    print(f"Manifest written:  {manifest_path}")
    print(f"Load map written:  {md_path}")


# ---------------------------------------------------------------------------
# Version loader
# ---------------------------------------------------------------------------

def load_version() -> str:
    kf_yaml = CORE_ROOT / "kf.yaml"
    if kf_yaml.exists():
        with open(kf_yaml, encoding="utf-8") as f:
            data = yaml.safe_load(f)
            return str(data.get("version", "unknown"))
    return "unknown"


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="KnowledgeForge compiler — core modules → variant repos"
    )
    parser.add_argument(
        "--target",
        required=True,
        choices=["claude-code", "claude-projects", "vscode", "plugin-bundle", "codex"],
        help="Platform target to compile for",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="Path to the target variant repo root",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview what would be written without writing",
    )
    parser.add_argument(
        "--diff",
        action="store_true",
        help="Show what has changed vs. current output repo (no writes)",
    )
    parser.add_argument(
        "--manifest",
        action="store_true",
        default=True,
        help="Write .kf-compile-manifest.json to output repo (default: true)",
    )
    parser.add_argument(
        "--check-divergence",
        action="store_true",
        help=(
            "Refuse to overwrite target files whose content differs from what the "
            "current compile would produce (compile-header timestamp drift ignored). "
            "Catches the case where a target file was hand-edited and the edits were "
            "never back-ported to core. Diverged files are skipped, not aborted; the "
            "process exits non-zero if any divergence was detected."
        ),
    )
    args = parser.parse_args()

    if args.dry_run and args.diff:
        sys.stderr.write("[kf-compile] --dry-run and --diff are mutually exclusive\n")
        sys.exit(1)
    if args.check_divergence and (args.dry_run or args.diff):
        sys.stderr.write(
            "[kf-compile] --check-divergence applies only to real writes "
            "(incompatible with --dry-run / --diff)\n"
        )
        sys.exit(1)

    output_root = Path(args.output).resolve()
    if not output_root.exists():
        sys.stderr.write(f"[kf-compile] Output directory not found: {output_root}\n")
        sys.exit(2)

    version = load_version()
    binding = load_binding(args.target)

    if args.target == "claude-code":
        manifest = compile_claude_code(
            binding, output_root, args.dry_run, args.diff, version,
            check_divergence=args.check_divergence,
        )
    elif args.target == "claude-projects":
        manifest = compile_claude_projects(
            binding, output_root, args.dry_run, args.diff, version,
            check_divergence=args.check_divergence,
        )
    elif args.target == "vscode":
        manifest = compile_vscode(
            binding, output_root, args.dry_run, args.diff, version,
            check_divergence=args.check_divergence,
        )
    elif args.target == "plugin-bundle":
        manifest = compile_plugin_bundle(
            binding, output_root, args.dry_run, args.diff, version,
            check_divergence=args.check_divergence,
        )
    elif args.target == "codex":
        # SPEC 1 D7 — Codex binding is deferred; placeholder emits no files,
        # writes a stderr warning, and exits 0 so CI/dry-runs don't false-fail.
        manifest = compile_codex_placeholder(
            binding, output_root, args.dry_run, args.diff, version,
            check_divergence=args.check_divergence,
        )
    else:
        sys.stderr.write(f"[kf-compile] Target '{args.target}' not yet implemented\n")
        sys.exit(1)

    print_manifest(manifest, args.target, args.dry_run, args.diff)

    if not args.dry_run and not args.diff and args.manifest:
        write_manifest(manifest, output_root, args.target, version)

    # Exit 1 if any sections were missing (signals incomplete module annotations)
    missing = sum(1 for e in manifest if e["status"] == "missing_section")
    if missing:
        sys.stderr.write(
            f"\n[kf-compile] {missing} output(s) skipped due to missing sections.\n"
            f"Add '## CC Skill' / '## CC Doc' / '## CC Agent' sections to modules.\n"
        )
        sys.exit(1)

    # Exit 2 if --check-divergence detected hand-edited target files.
    # Distinct exit code from missing_section so callers can tell them apart.
    diverged = [e for e in manifest if e.get("status") == "diverged"]
    if diverged:
        sys.stderr.write(
            f"\n[kf-compile] {len(diverged)} output(s) skipped — target has been hand-edited.\n"
            f"Back-port the changes to core/modules/, then re-run compile.\n"
        )
        for e in diverged:
            sys.stderr.write(
                f"  • {e['output']}  ({e.get('diverged_reason', 'unknown')})\n"
            )
        sys.exit(2)


if __name__ == "__main__":
    main()
