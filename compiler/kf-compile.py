#!/usr/bin/env python3
"""
kf-compile.py — KnowledgeForge compiler.

Reads canonical module specs from knowledgeforge-core/modules/, applies
platform bindings, and writes compiled output to a target variant repo.

Usage:
    python3 compiler/kf-compile.py --target claude-code --output /path/to/cc-repo
    python3 compiler/kf-compile.py --target claude-projects --output /path/to/cp-repo
    python3 compiler/kf-compile.py --target claude-code --output /path/to/cc-repo --dry-run
    python3 compiler/kf-compile.py --target claude-code --output /path/to/cc-repo --diff

Exit codes:
    0 — success
    1 — binding/module errors
    2 — output write errors
"""

import argparse
import json
import os
import re
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.stderr.write("[kf-compile] PyYAML required: pip install pyyaml\n")
    sys.exit(1)

# Resolve paths relative to this script (works regardless of cwd)
CORE_ROOT = Path(__file__).parent.parent
MODULES_DIR = CORE_ROOT / "modules"
BINDINGS_DIR = CORE_ROOT / "platform-bindings"
HOOKS_DIR = CORE_ROOT / "hooks"


# ---------------------------------------------------------------------------
# Section extraction
# ---------------------------------------------------------------------------


# Section names that delimit compilation blocks. The extractor only stops
# when it hits another CC marker — internal ## headings in embedded content
# are passed through unchanged.
CC_SECTION_MARKERS = frozenset({"CC Skill", "CC Doc", "CC Agent", "CC Rules"})

# Sections to STRIP from -CP output. Superset of CC_SECTION_MARKERS plus
# "Section-Load Map" — the latter only ever appears as a compile-side back-
# reference inside a CC body, but the strip filter names it explicitly as a
# safety net against future canonical drift (if it ever moves outside a CC
# block, it must still be stripped from -CP).
CP_STRIP_MARKERS = CC_SECTION_MARKERS | frozenset({"Section-Load Map"})


def extract_section(content: str, section_name: str) -> str | None:
    """
    Extract everything between '## {section_name}' and the next CC section marker.

    Stops only on '## CC Skill', '## CC Doc', '## CC Agent', '## CC Rules' —
    NOT on arbitrary ## headings inside the embedded content.

    Returns None if the section is not found.
    Strips leading/trailing whitespace from the extracted block.
    """
    lines = content.split("\n")
    in_section = False
    result = []

    for line in lines:
        stripped = line.strip()
        if stripped == f"## {section_name}":
            in_section = True
            continue
        if in_section:
            # Stop only at another CC section marker, not regular headings.
            # Also stops on titled variants (e.g., "## CC Skill — KF Fit Check")
            # by checking whether the suffix starts with a known marker followed
            # by a space (handles " — " and similar separators).
            if line.startswith("## "):
                section_id = line[3:].strip()
                if section_id in CC_SECTION_MARKERS or any(
                    section_id.startswith(m + " ") for m in CC_SECTION_MARKERS
                ):
                    break
            result.append(line)

    if not in_section:
        return None

    return "\n".join(result).strip()


def add_compile_header(content: str, source_module: str, output_type: str,
                        version: str) -> str:
    """Prepend a small compilation metadata comment to generated files.

    Deterministic: no timestamp. Per-run timestamp lives in
    .kf-compile-manifest.json which is the authoritative compile log.
    Embedding a timestamp here caused timestamp-only diffs to fire the
    cc/cp workflow change-detection and open noop PRs (bead `rxc`).
    """
    header = (
        f"<!-- Generated by kf-compile | source: {source_module} "
        f"| type: {output_type} | version: {version} -->\n"
    )
    return header + content


def heading_to_anchor(text: str) -> str:
    """Convert a markdown heading to a GitHub-compatible anchor.

    GitHub's algorithm: lowercase, strip all non-alphanumeric/space/hyphen chars,
    replace spaces with hyphens, collapse runs of hyphens.

    '## Full PDIA Method'  → '#full-pdia-method'
    '## Bias Detection'    → '#bias-detection'
    '## When to Calibrate' → '#when-to-calibrate'
    """
    anchor = text.lower()
    anchor = re.sub(r"[^\w\s-]", "", anchor)   # strip punctuation except hyphens
    anchor = re.sub(r"\s+", "-", anchor)        # spaces → hyphens
    anchor = re.sub(r"-{2,}", "-", anchor)      # collapse multiple hyphens
    return "#" + anchor.strip("-")


def generate_section_toc(content: str, min_headings: int = 2) -> str | None:
    """Generate a compact inline TOC from ## headings in extracted content.

    Returns a markdown line like:
        **Sections:** [When to Calibrate](#when-to-calibrate) · [Multi-Run Protocol](#multi-run-protocol)

    Returns None when fewer than min_headings ## headings are found (no point
    generating a TOC for a single-section file).

    Only indexes ## level — # (title) and ### (sub-items) are excluded.

    Headings containing '→' (navigation hints, file path references) have the
    path part stripped for display: 'Section-Load Map → ~/.claude/...' becomes
    'Section-Load Map' in the TOC link, anchored to the cleaned text.
    """
    headings = []
    for line in content.split("\n"):
        if line.startswith("## "):
            text = line[3:].strip()
            if not text:
                continue
            # Strip ' → path' suffixes — use only the label before the arrow
            display = text.split("→")[0].strip() if "→" in text else text
            headings.append((display, heading_to_anchor(display)))

    if len(headings) < min_headings:
        return None

    links = " · ".join(f"[{display}]({anchor})" for display, anchor in headings)
    return f"**Sections:** {links}"


def inject_toc(compiled_content: str, raw_content: str, out_type: str) -> str:
    """Inject a section TOC into compiled content after the compile header.

    Only fires for doc/skill/agent types with 2+ ## headings.
    Rules and verbatim copies are left unchanged.

    Placement:
    - Doc/Skill: TOC immediately after the compile header comment.
    - Agent: TOC after the YAML frontmatter block (--- ... ---) so the
      frontmatter stays machine-parseable at file top.
    """
    if out_type not in ("doc", "skill", "agent"):
        return compiled_content

    toc = generate_section_toc(raw_content)
    if toc is None:
        return compiled_content

    # compiled_content = "<!-- header -->\n{body}"
    header_line, body = compiled_content.split("\n", 1)

    if out_type == "agent":
        # Agent files have YAML frontmatter: ---\n...\n---\n
        # Inject TOC after the closing --- so frontmatter stays intact.
        body_stripped = body.lstrip("\n")
        if body_stripped.startswith("---\n"):
            closing = body_stripped.find("\n---\n", 4)
            if closing != -1:
                frontmatter = body_stripped[: closing + 5]   # up to and including ---\n
                rest = body_stripped[closing + 5 :]
                return f"{header_line}\n{frontmatter}\n{toc}\n\n---\n{rest}"
        # No frontmatter found — fall through to default placement

    return f"{header_line}\n\n{toc}\n\n---\n{body}"


def linkify_claude_paths(content: str, out_path: Path, output_root: Path) -> str:
    """Convert `~/.claude/path.md` references in Section-Load Maps to relative links.

    Maps `~/.claude/` → `{output_root}/.claude/` then computes a relative path
    from out_path's parent directory to the referenced file.

    Pattern forms handled:
      `~/.claude/X.md`              → [X.md](relative/X.md)
      `~/.claude/X.md` → Section   → [X.md#section-anchor](relative/X.md#section-anchor)

    The regex only matches backtick-delimited `~/.claude/` paths so false
    positives outside Section-Load Map blocks are negligible.
    """
    claude_root = output_root / ".claude"
    out_dir = out_path.parent

    def replace_path(match: re.Match) -> str:
        path_part = match.group(1)      # e.g., "skills/kf/builder.md"
        section_hint = match.group(2)   # e.g., "Builder accretion section" or None

        # Map ~/.claude/X → absolute target in variant repo
        abs_target = claude_root / path_part

        # Relative path from output file's directory to the target
        try:
            rel = Path(os.path.relpath(abs_target, out_dir)).as_posix()
        except ValueError:
            # Different drive on Windows — return original unchanged
            return match.group(0)

        display = Path(path_part).name

        anchor = ""
        if section_hint:
            anchor = heading_to_anchor(section_hint.strip())

        return f"[{display}]({rel}{anchor})"

    # Match: `~/.claude/{path.md}` optionally followed by ` → {section text}`
    # group 1: path after ~/.claude/
    # group 2: optional section name after →  (to end of line, non-greedy)
    pattern = r'`~/\.claude/([^`]+\.md)`(?:\s*→\s*([^\n`]+?))?(?=\s*\n|\s*$)'

    return re.sub(pattern, replace_path, content, flags=re.MULTILINE)


