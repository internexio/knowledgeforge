def load_module(module_num: str) -> tuple[str, str] | tuple[None, None]:
    """
    Load a module file by two-digit prefix number.

    Returns (filename, content) or (None, None) if not found.
    """
    pattern = f"{module_num}_*.md"
    matches = list(MODULES_DIR.glob(pattern))
    if not matches:
        return None, None
    return matches[0].name, matches[0].read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# Platform binding loader
# ---------------------------------------------------------------------------

def load_binding(target: str) -> dict:
    binding_path = BINDINGS_DIR / f"{target}.yaml"
    if not binding_path.exists():
        sys.stderr.write(f"[kf-compile] Binding not found: {binding_path}\n")
        sys.exit(1)
    with open(binding_path, encoding="utf-8") as f:
        return yaml.safe_load(f)


# ---------------------------------------------------------------------------
# Divergence detection
# ---------------------------------------------------------------------------

_COMPILE_HEADER_RE = re.compile(
    r"^<!-- Generated by kf-compile [^>]*-->\n", re.MULTILINE
)


def strip_compile_header(content: str) -> str:
    """Strip the kf-compile sentinel header so timestamp drift doesn't false-flag.

    Only removes the first match at the start of the file. Files without the
    header (e.g., claude-projects full-file output) pass through unchanged.
    """
    return _COMPILE_HEADER_RE.sub("", content, count=1)


def detect_divergence(out_path: Path, new_content: str) -> str | None:
    """Return a one-line reason if writing new_content would clobber hand edits.

    Compares body-of-existing to body-of-new (compile header stripped on both
    sides). If they differ in any non-header byte, the existing file has been
    edited outside the compile pipeline and overwriting would lose work.

    Returns None when overwrite is safe (file missing, or differs only by
    compile-header timestamp).
    """
    if not out_path.exists():
        return None
    try:
        existing = out_path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as e:
        return f"unreadable target ({e.__class__.__name__})"
    if strip_compile_header(existing) == strip_compile_header(new_content):
        return None
    old_lines = len(existing.splitlines())
    new_lines = len(new_content.splitlines())
    return f"hand-edited (target {old_lines} lines vs source {new_lines} lines)"


# ---------------------------------------------------------------------------
# Module-level frontmatter parser (cc_rules / cc_hooks — added 7.5.0)
# ---------------------------------------------------------------------------

_MODULE_METADATA_HEADING_RE = re.compile(r"^## Module Metadata\s*$", re.MULTILINE)
_YAML_FENCE_OPEN_RE = re.compile(r"^```yaml\s*$", re.MULTILINE)
_YAML_FENCE_CLOSE_RE = re.compile(r"^```\s*$", re.MULTILINE)


def parse_module_metadata(module_content: str) -> dict:
    """Extract and parse the YAML block right after '## Module Metadata'.

    Returns a dict like {"module": {...}, "cc_rules": [...], "cc_hooks": [...]}.
    Empty dict if no metadata block is found or YAML parse fails.
    """
    heading = _MODULE_METADATA_HEADING_RE.search(module_content)
    if not heading:
        return {}
    fence_open = _YAML_FENCE_OPEN_RE.search(module_content, heading.end())
    if not fence_open:
        return {}
    fence_close = _YAML_FENCE_CLOSE_RE.search(module_content, fence_open.end())
    if not fence_close:
        return {}
    yaml_text = module_content[fence_open.end():fence_close.start()]
    try:
        parsed = yaml.safe_load(yaml_text) or {}
        if not isinstance(parsed, dict):
            return {}
        return parsed
    except yaml.YAMLError as e:
        sys.stderr.write(f"[kf-compile] parse_module_metadata: YAML error — {e}\n")
        return {}


def emit_cc_rules_for_module(filename: str, module_content: str, metadata: dict,
                              output_root: Path, emit_fn,
                              version: str) -> list[Path]:
    """Compile cc_rules entries from a module's metadata into .claude/rules/kf/*.md.

    Each cc_rules entry produces one path-gated rule file with `paths:` frontmatter.
    body_section names the markdown section (e.g., "CC Rules — TypeScript imports")
    whose body is the rule content. Section heading convention uses `CC Rules — X`
    (plural) to match the existing CC_SECTION_MARKERS startswith logic.

    Returns the list of paths written (for orphan cleanup).
    """
    cc_rules = metadata.get("cc_rules") or []
    written = []
    for rule_entry in cc_rules:
        try:
            rule_filename = rule_entry["filename"]
            paths_globs = rule_entry["paths"]
            body_section = rule_entry["body_section"]
        except KeyError as e:
            sys.stderr.write(
                f"[kf-compile] cc_rules entry in {filename} missing required key {e}; "
                f"skipping entry\n"
            )
            continue

        out_path = output_root / ".claude/rules/kf" / rule_filename
        body = extract_section(module_content, body_section)
        if body is None:
            sys.stderr.write(
                f"[kf-compile] cc_rules: section '## {body_section}' not found in "
                f"{filename} — skipping {rule_filename}\n"
            )
            continue

        paths_yaml = yaml.safe_dump({"paths": paths_globs},
                                    default_flow_style=False,
                                    sort_keys=False).rstrip()
        header = (
            f"<!-- Generated by kf-compile from {filename} cc_rules: "
            f"{rule_filename} | version {version} -->\n"
        )
        content = f"{header}---\n{paths_yaml}\n---\n\n{body}"
        emit_fn(filename, out_path, content, f"cc_rules:{rule_filename}")
        written.append(out_path)
    return written


def cleanup_orphan_rules(written_paths: set[Path], rules_dir: Path,
                          output_root: Path, dry_run: bool, diff_mode: bool,
                          manifest: list[dict]) -> None:
    """Delete any pre-existing .md file in .claude/rules/kf/ not in written_paths.

    Compile is idempotent on this dir: removing a cc_rules entry from a module
    deletes the file on next compile. Subdirs are NOT recursed — kf-runtime/
    is a separate partition owned by the M21 accretion loop.
    """
    if not rules_dir.exists():
        return
    for existing in rules_dir.iterdir():
        if not existing.is_file() or existing.suffix != ".md":
            continue
        if existing in written_paths:
            continue
        rel = str(existing.relative_to(output_root))
        if dry_run or diff_mode:
            manifest.append({
                "source": "cc_rules:orphan_cleanup",
                "output": rel,
                "section": "orphan",
                "status": "would_delete",
            })
        else:
            existing.unlink()
            manifest.append({
                "source": "cc_rules:orphan_cleanup",
                "output": rel,
                "section": "orphan",
                "status": "deleted",
            })


def collect_cc_hooks_entry(filename: str, hook_entry: dict) -> tuple[str, dict] | None:
    """Validate a single cc_hooks entry and return (event, hook_dict).

    Returns None on malformed entry (logged to stderr).
    """
    try:
        event = hook_entry["hook_event"]
        command = hook_entry["command"]
    except KeyError as e:
        sys.stderr.write(
            f"[kf-compile] cc_hooks entry in {filename} missing required key {e}; "
            f"skipping entry\n"
        )
        return None

    built = {
        "type": hook_entry.get("type", "command"),
        "command": command,
        "matcher": hook_entry.get("matcher", {}),
    }
    source_rule = hook_entry.get("source_rule")
    if source_rule:
        built["_kf_source_rule"] = source_rule
    return event, built


def emit_settings_fragment(hooks_aggregate: dict, output_root: Path,
                            dry_run: bool, diff_mode: bool, manifest: list[dict],
                            version: str) -> None:
    """Write .claude/settings.kf.json if hooks_aggregate is non-empty; skip otherwise.

    Per Phase 2 spec Section 5: at v1 no module ships cc_hooks entries, so the
    aggregate is empty and we OMIT the file entirely (don't emit `{}`).
    """
    if not hooks_aggregate:
        return

    fragment = {
        "kf_hooks": hooks_aggregate,
        "_kf_compiled_at": datetime.now(timezone.utc).isoformat(),
        "_kf_version": version,
    }
    out_path = output_root / ".claude/settings.kf.json"
    content = json.dumps(fragment, indent=2) + "\n"
    rel = str(out_path.relative_to(output_root))
    entry = {
        "source": "cc_settings_fragment",
        "output": rel,
        "section": "compiled",
    }
    if dry_run:
        entry["status"] = "would_write"
    elif diff_mode:
        existing = out_path.read_text(encoding="utf-8") if out_path.exists() else ""
        entry["status"] = "unchanged" if content == existing else "changed"
    else:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(content, encoding="utf-8")
        entry["status"] = "written"
    entry["bytes"] = len(content.encode())
    manifest.append(entry)


# ---------------------------------------------------------------------------
# Compilers per platform
# ---------------------------------------------------------------------------

def compile_claude_code(binding: dict, output_root: Path, dry_run: bool,
                         diff_mode: bool, version: str,
                         check_divergence: bool = False) -> list[dict]:
    """
    Compile for the claude-code platform.

    Returns a manifest list: [{source, output, section, status, bytes}]
    """
    manifest = []

    def emit(source: str, out_path: Path, content: str, section: str):
        entry = {"source": source, "output": str(out_path.relative_to(output_root)),
                 "section": section}
        if diff_mode:
            existing = out_path.read_text(encoding="utf-8") if out_path.exists() else ""
            if content == existing:
                entry["status"] = "unchanged"
            else:
                entry["status"] = "changed"
                # Show a small diff summary
                old_lines = len(existing.splitlines())
                new_lines = len(content.splitlines())
                entry["diff_summary"] = f"{old_lines} → {new_lines} lines"
        elif dry_run:
            entry["status"] = "would_write"
        else:
            if check_divergence:
                reason = detect_divergence(out_path, content)
                if reason:
                    entry["status"] = "diverged"
                    entry["diverged_reason"] = reason
                    entry["bytes"] = len(content.encode())
                    manifest.append(entry)
                    return
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(content, encoding="utf-8")
            entry["status"] = "written"
        entry["bytes"] = len(content.encode())
        manifest.append(entry)

    module_outputs = binding.get("module_outputs", {})

    # Phase 2 (7.5.0) — per-module cc_rules accumulator + cross-module cc_hooks aggregator
    all_written_rules: set[Path] = set()
    cc_hooks_aggregate: dict[str, list[dict]] = {}

    for module_num, module_spec in module_outputs.items():
        filename, module_content = load_module(module_num)
        if module_content is None:
            sys.stderr.write(f"[kf-compile] Module {module_num} not found — skipping\n")
            continue

        for output_def in module_spec.get("outputs", []):
            out_type = output_def["type"]
            out_path = output_root / output_def["path"]
            section = output_def.get("section")

            if section:
                extracted = extract_section(module_content, section)
                if extracted is None:
                    sys.stderr.write(
                        f"[kf-compile] WARNING: section '## {section}' not found "
                        f"in {filename} — skipping {output_def['path']}\n"
                    )
                    manifest.append({
                        "source": filename,
                        "output": output_def["path"],
                        "section": section,
                        "status": "missing_section",
                    })
                    continue
                content = add_compile_header(extracted, filename, out_type, version)
                content = inject_toc(content, extracted, out_type)
                content = linkify_claude_paths(content, out_path, output_root)
            else:
                content = module_content

            emit(filename, out_path, content, section or "full")

        # Phase 2 — cc_rules + cc_hooks frontmatter passes
        metadata = parse_module_metadata(module_content)
        written = emit_cc_rules_for_module(
            filename, module_content, metadata, output_root, emit, version,
        )
        all_written_rules.update(written)

        for hook_entry in (metadata.get("cc_hooks") or []):
            result = collect_cc_hooks_entry(filename, hook_entry)
            if result is None:
                continue
            event, built = result
            cc_hooks_aggregate.setdefault(event, []).append(built)

    # Phase 2 — orphan cleanup for .claude/rules/kf/
    cleanup_orphan_rules(
        all_written_rules,
        output_root / ".claude/rules/kf",
        output_root,
        dry_run,
        diff_mode,
        manifest,
    )

    # Phase 2 — emit settings.kf.json (omitted entirely if hooks aggregate is empty)
    emit_settings_fragment(
        cc_hooks_aggregate, output_root, dry_run, diff_mode, manifest, version,
    )

    # Hooks — copy verbatim
    special = binding.get("special_outputs", {})
    hooks_spec = special.get("hooks", {})
    if hooks_spec and not dry_run and not diff_mode:
        hooks_dest = output_root / binding["output_structure"]["hooks_dir"]
        hooks_dest.mkdir(parents=True, exist_ok=True)
        for hook_file in hooks_spec.get("files", []):
            src = HOOKS_DIR / hook_file
            if src.exists():
                dst = hooks_dest / hook_file
                shutil.copy2(src, dst)
                manifest.append({
                    "source": f"hooks/{hook_file}",
                    "output": str((hooks_dest / hook_file).relative_to(output_root)),
                    "section": "copy",
                    "status": "written",
                    "bytes": src.stat().st_size,
                })
            else:
                sys.stderr.write(f"[kf-compile] Hook not found: {src}\n")
    elif hooks_spec:
        for hook_file in hooks_spec.get("files", []):
            manifest.append({
                "source": f"hooks/{hook_file}",
                "output": str(Path(binding["output_structure"]["hooks_dir"]) / hook_file),
                "section": "copy",
                "status": "would_write" if dry_run else "diff_skipped",
            })

    # Item C3 fail-closed -CC guard — only runs on real writes (dry_run / diff
    # don't produce on-disk artifacts to inspect).
    if not dry_run and not diff_mode:
        assert_cc_invariants(binding, output_root)

    return manifest


# Routable agents that DON'T derive from a `@delegate` token in the M00
# routing table — they are emitted bodies but never appear as @-tokens.
#   kf.md                = the orchestrator's own body (no self-delegation)
#   knowledge-librarian  = utility agent dispatched by the accretion pipeline,
#                          not by the routing table
CC_NON_ROUTABLE_AGENTS = frozenset({"kf", "knowledge-librarian"})


def assert_cc_invariants(binding: dict, output_root: Path) -> None:
    """Fail-closed -CC guard (Item C3).

    Three invariants enforced after a real write:
    (a) Every mode-agent module declared in module_outputs that emits an agent
        artifact actually produced .claude/agents/<name>.md on disk.
    (b) adversarial-critic.md contains the 'Untrusted Input Boundary' clause
        (SPEC 1 prompt-level defense — see Module 07 ## CC Agent (Adversarial
        Variant), Module 00 ## Automatic Adversarial Verification, Module 20
        verifier_tool_tier_policy).
    (c) The set of `@delegate` tokens in the orchestrator routing table
        (Module 00) is exactly the set of routable agent bodies on disk
        (.claude/agents/*.md minus CC_NON_ROUTABLE_AGENTS). No orphans either
        direction.

    Raises RuntimeError naming the failing invariant + missing artifact.
    """
    agents_dir = output_root / binding["output_structure"]["agents_dir"]

    # (a) Every declared agent output for a mode module exists on disk.
    for mod_id, mod_spec in binding.get("module_outputs", {}).items():
        for out_spec in mod_spec.get("outputs", []):
            if out_spec.get("type") != "agent":
                continue
            rel = out_spec["path"]
            target = output_root / rel
            if not target.exists():
                raise RuntimeError(
                    f"[kf-compile][-CC guard] Module '{mod_id}' declared agent "
                    f"output {rel} but no file was written. Check whether the "
                    f"module's ## {out_spec.get('section')} section exists and "
                    f"non-empty."
                )

    # (b) adversarial-critic must carry the Untrusted Input Boundary clause.
    adv = agents_dir / "adversarial-critic.md"
    if not adv.exists():
        raise RuntimeError(
            "[kf-compile][-CC guard] adversarial-critic.md missing — SPEC 1 "
            "verifier-promotion did not land. Re-author Module 07 ## CC Agent "
            "(Adversarial Variant)."
        )
    if "Untrusted Input Boundary" not in adv.read_text(encoding="utf-8"):
        raise RuntimeError(
            "[kf-compile][-CC guard] adversarial-critic.md is missing the "
            "'Untrusted Input Boundary' clause. The prompt-level defense for "
            "the adversarial verifier is required by SPEC 1; re-author the "
            "clause in Module 07 ## CC Agent (Adversarial Variant)."
        )

    # (c) Delegates ↔ routable agents bijection (no orphans).
    m00 = next(MODULES_DIR.glob("00_*.md"), None)
    if m00 is None:
        raise RuntimeError("[kf-compile][-CC guard] Module 00 not found.")
    m00_body = m00.read_text(encoding="utf-8")
    delegates = set(re.findall(r"@([a-z][a-z-]+)", m00_body))
    routable_bodies = {
        p.stem for p in agents_dir.glob("*.md")
        if p.stem not in CC_NON_ROUTABLE_AGENTS
    }
    missing_bodies = delegates - routable_bodies
    if missing_bodies:
        raise RuntimeError(
            f"[kf-compile][-CC guard] Delegate(s) in M00 routing table without "
            f"a compiled agent body: {sorted(missing_bodies)}. Either author "
            f"the ## CC Agent section in the corresponding module, or remove "
            f"the @delegate from the routing table."
        )
    orphan_bodies = routable_bodies - delegates
    if orphan_bodies:
        raise RuntimeError(
            f"[kf-compile][-CC guard] Compiled agent body without a matching "
            f"@delegate in M00 routing table: {sorted(orphan_bodies)}. Either "
            f"add the @delegate to M00 (if the agent is user-routable) or add "
            f"the agent name to CC_NON_ROUTABLE_AGENTS (utility/self body)."
        )


def strip_cc_sections(content: str) -> str:
    """
    Remove CC compilation sections from module content before writing to CP.

    Cuts the file at the first occurrence of any marker in CP_STRIP_MARKERS
    (## CC Skill / ## CC Doc / ## CC Agent / ## CC Rules / ## Section-Load Map,
    plus titled variants like '## CC Agent (Adversarial Variant)' or
    '## CC Skill — KF Fit Check'). The embed script appends CC sections at
    the end of modules so a single forward cut is sound; the Section-Load Map
    addition is defense-in-depth against canonical drift.
    """
    lines = content.split("\n")
    cut_at = len(lines)

    for i, line in enumerate(lines):
        if not line.startswith("## "):
            continue
        section_id = line[3:].strip()
        if section_id in CP_STRIP_MARKERS or any(
            section_id.startswith(m + " ") or section_id.startswith(m + " (")
            for m in CP_STRIP_MARKERS
        ):
            cut_at = i
            break

    stripped = "\n".join(lines[:cut_at]).rstrip("\n") + "\n"
    return stripped


def assert_cp_clean(out_path: Path, content: str) -> None:
    """Fail-closed -CP guard (Item B3).

    Scan content for any forbidden compilation-section heading. Raises
    RuntimeError naming the offending file + line if one slips through.
    Called from compile_claude_projects() after each file write so the
    -CP publish reliably rejects CC leakage even if strip_cc_sections
    misses a future variant.
    """
    for lineno, line in enumerate(content.split("\n"), start=1):
        if not line.startswith("## "):
            continue
        section_id = line[3:].strip()
        if section_id in CP_STRIP_MARKERS or any(
            section_id.startswith(m + " ") or section_id.startswith(m + " (")
            for m in CP_STRIP_MARKERS
        ):
            raise RuntimeError(
                f"[kf-compile][-CP guard] FORBIDDEN section leaked into "
                f"{out_path.name} at line {lineno}: '{line.rstrip()}'. "
                f"strip_cc_sections did not catch it. Fix the strip filter "
                f"before re-publishing."
            )


def compile_vscode(binding: dict, output_root: Path, dry_run: bool,
                   diff_mode: bool, version: str,
                   check_divergence: bool = False) -> list[dict]:
    """
    Compile for the vscode platform.

    VS Code uses verbatim module copy — each mode module is emitted as a
    complete .md resource file loaded at runtime by the extension host.
    Infrastructure modules (12–25) are NOT compiled; their behaviours are
    embedded in KFSession TypeScript.

    special_outputs.mode_registry is written as a JSON file.
    """
    manifest = []
    module_outputs = binding.get("module_outputs", {})
    special = binding.get("special_outputs", {})

    # --- Mode resource files ---
    for mod_id, mod_spec in module_outputs.items():
        outputs = mod_spec.get("outputs", [])
        for out_spec in outputs:
            if out_spec.get("type") != "resource":
                continue

            rel_path = out_spec["path"]
            out_path = output_root / rel_path

            # Find source module by prefix (e.g. "00" → 00_orchestrator.md)
            candidates = list(MODULES_DIR.glob(f"{mod_id}_*.md"))
            if not candidates:
                sys.stderr.write(
                    f"[kf-compile] Module '{mod_id}' not found — skipping\n"
                )
                manifest.append({
                    "source": f"{mod_id}_*.md",
                    "output": rel_path,
                    "section": "verbatim",
                    "status": "missing_module",
                })
                continue

            src = candidates[0]
            content = src.read_text(encoding="utf-8")
            entry = {
                "source": src.name,
                "output": rel_path,
                "section": "verbatim",
            }

            if diff_mode:
                existing = out_path.read_text(encoding="utf-8") if out_path.exists() else ""
                if content == existing:
                    entry["status"] = "unchanged"
                else:
                    entry["status"] = "changed"
                    entry["diff_summary"] = (
                        f"{len(existing.splitlines())} → {len(content.splitlines())} lines"
                    )
            elif dry_run:
                entry["status"] = "would_write"
            else:
                if check_divergence:
                    reason = detect_divergence(out_path, content)
                    if reason:
                        entry["status"] = "diverged"
                        entry["diverged_reason"] = reason
                        entry["bytes"] = len(content.encode())
                        manifest.append(entry)
                        continue
                out_path.parent.mkdir(parents=True, exist_ok=True)
                out_path.write_text(content, encoding="utf-8")
                entry["status"] = "written"

            entry["bytes"] = len(content.encode())
            manifest.append(entry)

    # --- special_outputs.mode_registry ---
    registry_spec = special.get("mode_registry", {})
    if registry_spec:
        reg_path = output_root / registry_spec["path"]
        reg_content = registry_spec.get("content", "")
        entry = {
            "source": "platform-bindings/vscode.yaml",
            "output": registry_spec["path"],
            "section": "mode_registry",
        }

        if diff_mode:
            existing = reg_path.read_text(encoding="utf-8") if reg_path.exists() else ""
            entry["status"] = "unchanged" if reg_content.strip() == existing.strip() else "changed"
        elif dry_run:
            entry["status"] = "would_write"
        else:
            normalized = reg_content.strip() + "\n"
            if check_divergence:
                reason = detect_divergence(reg_path, normalized)
                if reason:
                    entry["status"] = "diverged"
                    entry["diverged_reason"] = reason
                    entry["bytes"] = len(reg_content.encode())
                    manifest.append(entry)
                    return manifest
            reg_path.parent.mkdir(parents=True, exist_ok=True)
            reg_path.write_text(normalized, encoding="utf-8")
            entry["status"] = "written"

        entry["bytes"] = len(reg_content.encode())
        manifest.append(entry)

    return manifest


